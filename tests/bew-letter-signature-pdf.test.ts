/* ------------------------------------------------------------------ *
 * Shared layout assertions (raw drawing order + geometry)
 * ------------------------------------------------------------------ */

async function expectSignatureLayout(bytes: Uint8Array, expected: { width: number; height: number; ratio: number }) {
  // A real, valid, single A4 page.
  expect(new TextDecoder("latin1").decode(bytes.subarray(0, 5))).toBe("%PDF-");
  const doc = await PDFDocument.load(bytes);
  expect(doc.getPageCount()).toBe(1);
  const size = doc.getPage(0).getSize();
  expect(size.width).toBeCloseTo(595.28, 0);
  expect(size.height).toBeCloseTo(841.89, 0);

  const items = await streamItems(bytes);
  const closing = items.find((i) => i.kind === "text" && i.text === CLOSING);
  // Exact title-case match: the top-right sender header is UPPERCASE
  // ("MUSTAPHA DRIF"), so this uniquely identifies the printed signature line.
  const name = items.find((i) => i.kind === "text" && i.text === NAME);
  const images = items.filter((i) => i.kind === "image");

  expect(closing, `closing "${CLOSING}" must be drawn`).toBeTruthy();
  expect(name, `printed name "${NAME}" must be drawn`).toBeTruthy();
  expect(images, "exactly one image (the signature) must be embedded").toHaveLength(1);
  const closingItem = closing!;
  const nameItem = name!;
  const img = images[0];

  // 1) ORDER in the actual PDF drawing order: closing → name → image.
  expect(closingItem.order).toBeLessThan(nameItem.order);
  expect(nameItem.order).toBeLessThan(img.order);

  // 2) POSITION: the image is BELOW the name (its top under the name's
  //    baseline — no overlap, never above), the name below the closing.
  expect(img.y + img.height).toBeLessThan(nameItem.y);
  expect(nameItem.y).toBeLessThan(closingItem.y);

  // 3) LEFT-ALIGNED with the printed name, at the 65 pt content margin.
  expect(img.x).toBeCloseTo(nameItem.x, 6);
  expect(img.x).toBeCloseTo(65, 6);

  // 4) SIZE: the expected display box (aspect ratio preserved by design)…
  expect(img.width).toBeCloseTo(expected.width, 2);
  expect(img.height).toBeCloseTo(expected.height, 2);
  expect(img.width / img.height).toBeCloseTo(expected.ratio, 4);
  // …inside the new maximums…
  expect(img.width).toBeLessThanOrEqual(NEW_MAX_WIDTH + 1e-6);
  expect(img.height).toBeLessThanOrEqual(NEW_MAX_HEIGHT + 1e-6);
  // …and strictly LARGER than the legacy 72 × 26 pt maximum in BOTH
  // dimensions (this source aspect ratio permits it).
  expect(img.width).toBeGreaterThan(OLD_MAX_WIDTH);
  expect(img.height).toBeGreaterThan(OLD_MAX_HEIGHT);

  // 5) No borders/backgrounds/decoration: no rectangle operator anywhere
  //    in the content stream.
  expect(tokenizeStream(await contentStreamOf(bytes))).not.toContain("re");
}

/* ------------------------------------------------------------------ *
 * A. The genuine signature image: order, size, placement
 * ------------------------------------------------------------------ */

describe("Anschreiben signature image — order, size, placement (raw content stream)", () => {
  it("PNG: closing → printed name → signature image BELOW the name, in the actual drawing order", async () => {
    const bytes = await generateLetterPdf(folioWith({ bytes: WIDE_PNG, mime: "image/png" }), { singlePage: true });
    // 480 × 140 px fitted into the 130 × 44 pt box → the width cap binds:
    // 130 × (140/480) = 130 × 37.92 pt (the legacy box would have shown 72 × 21 pt).
    await expectSignatureLayout(bytes, { width: 130, height: 130 * 140 / 480, ratio: WIDE_RATIO });
  }, 15000);

  it("JPEG: same order, geometry and size with a JPEG signature", async () => {
    const bytes = await generateLetterPdf(folioWith({ bytes: WIDE_JPG, mime: "image/jpeg" }), { singlePage: true });
    await expectSignatureLayout(bytes, { width: 130, height: 130 * 140 / 480, ratio: WIDE_RATIO });
  }, 15000);

  it("a less-wide signature is bounded by the HEIGHT cap, aspect ratio intact", async () => {
    const bytes = await generateLetterPdf(folioWith({ bytes: MEDIUM_PNG, mime: "image/png" }), { singlePage: true });
    // 320 × 140 px: min(130/320, 44/140) → the 44 pt height cap binds:
    // 44 × (320/140) = 100.57 × 44 pt (legacy: 59.43 × 26 pt).
    await expectSignatureLayout(bytes, { width: 44 * 320 / 140, height: 44, ratio: MEDIUM_RATIO });
  }, 15000);

  it("no uploaded signature → valid single-page letter with the printed name, no image, classic blank space", async () => {
    const bytes = await generateLetterPdf(folioWith(undefined)); // default (11 pt) mode
    expect(new TextDecoder("latin1").decode(bytes.subarray(0, 5))).toBe("%PDF-");
    const doc = await PDFDocument.load(bytes);
    expect(doc.getPageCount()).toBe(1);

    const items = await streamItems(bytes);
    expect(items.filter((i) => i.kind === "image")).toHaveLength(0);
    const closing = items.find((i) => i.kind === "text" && i.text === CLOSING);
    const name = items.find((i) => i.kind === "text" && i.text === NAME);
    expect(closing).toBeTruthy();
    expect(name).toBeTruthy();
    // The classic layout without an image is unchanged: 34 pt of blank
    // signature space between the closing and the printed name
    // (lineH 15.5 at the reference 11 pt).
    expect(closing!.y - name!.y).toBeCloseTo(15.5 + 34, 5);
  }, 15000);
});

/* ------------------------------------------------------------------ *
 * B. Pagination — the larger image never clips or splits the block
 * ------------------------------------------------------------------ */

describe("Anschreiben signature image — pagination with the larger image", () => {
  it("long letter + signature → ONE A4 page, every paragraph present, nothing below the bottom margin", async () => {
    const paragraphs = [
      "hiermit bewerbe ich mich um den Ausbildungsplatz in Ihrem Unternehmen und bringe Erfahrung im Anlagenbau mit.",
      "In meiner bisherigen Ausbildung habe ich gelernt, technische Anlagen fachgerecht zu warten und Inbetriebnahmen durchzuführen.",
      "Ich arbeite sorgfältig, zuverlässig und gerne im Team. Neue Aufgaben nehme ich motiviert an.",
      "Ihr Unternehmen hat mich durch die moderne technische Ausstattung und die gute Einarbeitung besonders angesprochen.",
      "Über eine Einladung zu einem persönlichen Gespräch würde ich mich sehr freuen und stehe für Rückfragen gerne zur Verfügung.",
    ];
    const bodyHtml =
      "<p>Sehr geehrte Frau Schneider,</p>" +
      paragraphs.map((p) => `<p>${p}</p>`).join("") +
      `<p>${CLOSING}</p><p>${NAME}</p>`;
    const bytes = await generateLetterPdf(folioWith({ bytes: WIDE_PNG, mime: "image/png" }, bodyHtml), { singlePage: true });

    const doc = await PDFDocument.load(bytes);
    expect(doc.getPageCount(), "the whole letter must stay on one A4 page").toBe(1);

    const items = await streamItems(bytes);
    // NO paragraph was removed — every body sentence is present.
    const allText = items.filter((i) => i.kind === "text").map((i) => i.text).join(" ");
    for (const p of paragraphs) {
      // The body is drawn word-by-word (justification), so match the
      // distinctive opening words of each paragraph.
      const head = p.split(" ").slice(0, 5).join(" ");
      expect(allText.replace(/\s+/g, " "), `missing paragraph start "${head}"`).toContain(head);
    }
    // The signature group is intact and in order.
    const closing = items.find((i) => i.kind === "text" && i.text === CLOSING);
    const name = items.find((i) => i.kind === "text" && i.text === NAME);
    const img = items.find((i) => i.kind === "image");
    expect(closing).toBeTruthy();
    expect(name).toBeTruthy();
    expect(img, "the signature image must be embedded").toBeTruthy();
    expect(closing!.order).toBeLessThan(name!.order);
    expect(name!.order).toBeLessThan(img!.order);

    // Nothing (text baseline or image bottom) dips below the 64 pt bottom margin.
    for (const i of items) {
      expect(i.y, `item "${i.kind === "image" ? i.name : i.text}" below the bottom margin`).toBeGreaterThanOrEqual(64 - 1e-6);
    }
  }, 20000);

  it("multi-page letter (default mode) keeps closing + name + image together on the LAST page", async () => {
    const longBody =
      "<p>Sehr geehrte Frau Schneider,</p>" +
      Array.from({ length: 12 }, (_, i) =>
        `<p>Absatz ${i + 1}: ${"Hier folgt fundierter, praxisnaher Inhalt. ".repeat(7)}</p>`,
      ).join("") +
      `<p>${CLOSING}</p><p>${NAME}</p>`;
    const bytes = await generateLetterPdf(folioWith({ bytes: WIDE_PNG, mime: "image/png" }, longBody));

    const doc = await PDFDocument.load(bytes);
    const pageCount = doc.getPageCount();
    expect(pageCount).toBeGreaterThanOrEqual(2);

    // The signature group is NOT on page 1…
    const firstPageImages = (await streamItems(bytes, 0)).filter((i) => i.kind === "image");
    expect(firstPageImages).toHaveLength(0);
    // …it is complete on the LAST page, in the required order.
    const last = await streamItems(bytes, pageCount - 1);
    const closing = last.find((i) => i.kind === "text" && i.text === CLOSING);
    const name = last.find((i) => i.kind === "text" && i.text === NAME);
    const img = last.find((i) => i.kind === "image");
    expect(closing, "closing on the last page").toBeTruthy();
    expect(name, "printed name on the last page").toBeTruthy();
    expect(img, "signature image on the last page").toBeTruthy();
    expect(closing!.order).toBeLessThan(name!.order);
    expect(name!.order).toBeLessThan(img!.order);
    expect(img!.y).toBeGreaterThanOrEqual(64 - 1e-6); // no bottom clipping
  }, 30000);
});

/* ------------------------------------------------------------------ *
 * C. CV PDFs are completely unaffected
 * ------------------------------------------------------------------ */

describe("CV PDFs never contain the signature", () => {
  it("a generated CV carries no embedded image at all (parsed content streams)", async () => {
    const cv: CvDocument = cvEmpty();
    cv.personal = { ...cv.personal, fullName: NAME };
    const bytes = await generateCvPdf(cv);

    expect(new TextDecoder("latin1").decode(bytes.subarray(0, 5))).toBe("%PDF-");
    const doc = await PDFDocument.load(bytes);
    expect(doc.getPageCount()).toBeGreaterThanOrEqual(1);
    for (let p = 0; p < doc.getPageCount(); p++) {
      const items = await streamItems(bytes, p);
      expect(items.filter((i) => i.kind === "image"), `page ${p + 1} must embed no image`).toHaveLength(0);
    }
    // Defence in depth: no image XObject at all in the file.
    expect(Buffer.from(bytes).toString("latin1")).not.toContain("/Subtype /Image");
  }, 15000);
});

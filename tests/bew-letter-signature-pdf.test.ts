/**
 * Anschreiben PDF — signature image LAYOUT regression suite.
 *
 * THE CONTRACT THIS SUITE PINS (confirmed against the user's actual PDF):
 *   1. ORDER: closing ("Mit freundlichen Grüßen") → applicant's complete
 *      printed name → the genuine uploaded signature image BELOW the name.
 *      The image must NEVER appear above the name or between the closing
 *      and the name.
 *   2. SIZE: the signature displays at up to 130 × 44 PDF points (the legacy
 *      maximum was 72 × 26 pt) — clearly readable — and is strictly larger
 *      than the legacy maximum whenever the source aspect ratio permits it.
 *   3. FIDELITY: original aspect ratio preserved (never stretched, distorted
 *      or cropped); left-aligned with the printed name; no borders,
 *      backgrounds or other decoration.
 *   4. PAGINATION: the closing group (closing + name + image) is kept
 *      together, nothing clips at the bottom margin, normal letters stay a
 *      single A4 page and NO paragraph is ever removed.
 *   5. DEGRADATION: no uploaded signature → still a valid letter with the
 *      printed name (classic blank signature space, layout unchanged).
 *   6. CV PDFs are completely unaffected — the CV renderer never embeds the
 *      signature.
 *
 * VERIFICATION METHOD: real decodable PNG/JPEG fixtures
 * (tests/fixtures/signature-wide.png / .jpg / signature-medium.png —
 * generated by scripts/generate-signature-fixture.mjs) rendered through the
 * REAL renderer, then asserted against the RAW PAGE CONTENT STREAM: the
 * actual PDF operators in drawing order (text items with their Tm position,
 * image paint ops with their composite CTM → exact x/y/width/height in
 * points). NOT a "/Subtype /Image" string check.
 */
